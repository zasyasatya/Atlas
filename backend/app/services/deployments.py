"""One-click deployment engine for Streamlit / Gradio bundles.

Drivers:
  local_process - run the app as a child process on an allocated port (default; great for demos)
  coolify       - create/deploy an application through the Coolify API
  manifest      - only generate Dockerfile + compose, no execution (air-gapped review)

Every bundle gets a generated Dockerfile so the exact same artifact can be
handed to Coolify, Fly, Render or plain `docker run`.
"""
from __future__ import annotations

import os
import re
import shutil
import signal
import socket
import subprocess
import sys
import time
import zipfile
from datetime import datetime, timezone
from pathlib import Path

import httpx
